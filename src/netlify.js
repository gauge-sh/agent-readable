import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { parse, stringify } from 'smol-toml';
import { rejectSymlinks, validateConfig } from './config.js';
import { createNetlifyHandler } from './netlify-edge.js';
import { prefersMarkdown } from './runtime.js';
import { parseUserAgents, markdownRejection } from './user-agents.js';

export const netlifyOutput = '.netlify/agent-readable/output';
const edgePath = '.netlify/v1/edge-functions/agent-readable.js';
const signature = '// Generated by agent-readable.\n';

export async function validateNetlifyOutput(cwd) {
  const file = path.join(cwd, edgePath);
  await rejectSymlinks(cwd, file);
  try {
    if (!(await readFile(file, 'utf8')).startsWith(signature)) throw new Error(`Refusing to replace an existing ${edgePath} not generated by agent-readable.`);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
}

export async function writeNetlifyEdge(cwd, pages, config, llms) {
  const { include, exclude } = parseUserAgents(config.userAgents);
  const source = signature + `const prefersMarkdown = ${prefersMarkdown.toString()};\nconst createNetlifyHandler = ${createNetlifyHandler.toString()};\nexport default createNetlifyHandler(${JSON.stringify(pages.map(({ route, markdown }) => ({ route, markdown })))}, ${JSON.stringify(include.map(re => [re.source, re.flags]))}, ${JSON.stringify(exclude.map(re => [re.source, re.flags]))}, ${JSON.stringify(markdownRejection)}, prefersMarkdown, ${Boolean(llms)});\nexport const config = { path: "/*" };\n`;
  const file = path.join(cwd, edgePath);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, source);
}

export async function setupNetlify(cwd, buildCommand) {
  if (typeof buildCommand !== 'string' || !buildCommand.trim() || /\bagent-readable\b/.test(buildCommand)) throw new Error('setup-netlify requires the static site --build-command without agent-readable.');
  const configFile = path.join(cwd, 'agent-readable.json');
  const config = JSON.parse(await readFile(configFile, 'utf8'));
  validateConfig(config, cwd);
  const file = path.join(cwd, 'netlify.toml');
  await rejectSymlinks(cwd, file);
  await rejectSymlinks(cwd, configFile);
  let previous = {};
  try { previous = parse(await readFile(file, 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous.build?.base && previous.build.base !== '.') throw new Error('Run setup-netlify in the Netlify build base and configure monorepo settings manually.');
  for (const context of Object.values(previous.context || {})) {
    if (context.command || context.publish || context.base) throw new Error('Context-specific Netlify build settings require manual configuration. Set each publish directory and append agent-readable build --target netlify.');
  }
  previous.build = { ...previous.build, command: `(${buildCommand.trim()}) && npx --no-install agent-readable build --target netlify`, publish: `${netlifyOutput}/static` };
  await writeFile(file, stringify(previous));
  await writeFile(configFile, JSON.stringify({ ...config, target: 'netlify' }, null, 2) + '\n');
  return previous;
}
